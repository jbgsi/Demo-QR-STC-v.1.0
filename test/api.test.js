import test from 'node:test';
import assert from 'node:assert/strict';
import { createApp } from '../src/app.js';
import { Store, TTL } from '../src/store.js';

test('HTTP: authentication, local upload, QR handoff, cancellation, limits, expiration and logout', async t => {
  let time = Date.now();
  const store = new Store(() => time);
  const app = createApp({ store, publicBaseUrl: 'http://192.168.1.50:3000' });
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => { app.locals.dispose(); server.closeAllConnections(); server.close(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  let cookie = '';
  async function request(path, body, authenticated = true) {
    const headers = {};
    if (authenticated && cookie) headers.Cookie = cookie;
    if (body && !(body instanceof FormData)) headers['Content-Type'] = 'application/json';
    const response = await fetch(base + path, { method: body === undefined ? 'GET' : 'POST', headers, body: body instanceof FormData ? body : body === undefined ? undefined : JSON.stringify(body) });
    if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
    return { status: response.status, data: await response.json() };
  }
  function files(size = 100, type = 'application/pdf') { const data = Buffer.alloc(size, 32); data.write('%PDF-1.7\n'); data.write('\n%%EOF\n', size - 7); const form = new FormData(); form.append('files', new Blob([data], { type }), 'cedula.pdf'); return form; }
  assert.equal((await request('/api/session')).status, 401);
  assert.equal((await request('/api/login', { username: 'admin', password: 'wrong' })).status, 401);
  assert.equal((await request('/api/login', { username: 'admin', password: 'admin' })).status, 200);
  const initial = (await request('/api/session')).data;
  await request('/api/start/local', {});
  assert.equal((await request('/api/complete', {})).status, 409);
  assert.equal((await request('/api/files', files(5 * 1024 * 1024))).status, 200);
  assert.equal((await request('/api/files', files(5 * 1024 * 1024 + 1))).status, 400);
  // Browser MIME is untrusted: genuine PDF content is recognized independently.
  const spoof = new FormData(); spoof.append('files', new Blob(['<script>not an image</script>'], {type:'image/png'}), 'fake.png');
  assert.equal((await request('/api/files', spoof)).status, 400);
  const uploaded = (await request('/api/session')).data.files[0];
  assert.equal((await request('/api/complete', {})).status, 409);
  const preview = await fetch(base + `/api/files/${uploaded.id}/content`, { headers: { Cookie: cookie } });
  assert.equal(preview.status, 200);
  assert.equal(preview.headers.get('content-type'), 'application/pdf');
  assert.equal((await preview.arrayBuffer()).byteLength, 5 * 1024 * 1024);
  assert.equal((await fetch(base + `/api/files/${uploaded.id}/content`)).status, 401);
  await request(`/api/files/${uploaded.id}/review`, {});
  let result = await request('/api/complete', {});
  assert.equal(result.data.status, 'complete');
  assert.equal(result.data.id, initial.id);
  assert.equal((await request('/api/start/mobile', {})).status, 409);
  await request('/api/new', {});
  result = await request('/api/start/mobile', {});
  assert.match(result.data.qr, /^data:image\/png;base64,/);
  let token = result.data.url.split('/').pop();
  const mobileId = result.data.id;
  assert.equal((await request(`/api/mobile/${token}`, undefined, false)).data.id, mobileId);
  assert.equal((await request(`/api/mobile/${token}/files`, files(), false)).status, 200);
  assert.equal((await request('/api/session')).data.files.length, 1);
  assert.equal((await request(`/api/mobile/${token}/complete`, {}, false)).status, 409);
  const mobileFile = (await request('/api/session')).data.files[0];
  const mobilePreview = await fetch(base + `/api/mobile/${token}/files/${mobileFile.id}/content`);
  assert.equal(mobilePreview.status, 200);
  await request(`/api/mobile/${token}/files/${mobileFile.id}/review`, {}, false);
  assert.equal((await request('/api/session')).data.files[0].reviewed, true);
  assert.equal((await request(`/api/mobile/${token}/complete`, {}, false)).status, 200);
  assert.equal((await request('/api/session')).data.status, 'complete');
  assert.equal((await request(`/api/mobile/${token}`, undefined, false)).status, 410);
  await request('/api/new', {});
  token = (await request('/api/start/mobile', {})).data.url.split('/').pop();
  await request(`/api/mobile/${token}/cancel`, {}, false);
  assert.equal((await request('/api/session')).data.status, 'idle');
  assert.equal((await request(`/api/mobile/${token}/files`, files(), false)).status, 410);
  token = (await request('/api/start/mobile', {})).data.url.split('/').pop();
  time += TTL;
  assert.equal((await request(`/api/mobile/${token}`, undefined, false)).status, 410);
  assert.equal((await request('/api/session')).data.reason, 'expired');
  token = (await request('/api/start/mobile', {})).data.url.split('/').pop();
  const crossOrigin = await fetch(base + '/api/cancel', { method: 'POST', headers: { Cookie: cookie, Origin: 'https://other.example' } });
  assert.equal(crossOrigin.status, 403);
  await request('/api/logout', {});
  assert.equal((await request('/api/session')).status, 401);
  assert.equal((await request(`/api/mobile/${token}`, undefined, false)).status, 410);
});
